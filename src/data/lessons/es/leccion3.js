//   - Ex. 2 and 3: one answer per switch of person or verb. tú → yo, usted →
//     yo (with el mapa, an exception to the gender rule), ustedes →
//     nosotros, tu → mi, a plural noun, ser with tú, and estar with a thing.
//     "¿Estás cansado?" and "¿Vas a la playa?" are Lección 2's questions
//     again, and "¿Estás cansado? → Sí, …" is already Lección 2's card.
//   - Ex. 4 (write el / la / los / las and un / una / unos / unas) becomes
//     one exact gap card per article, on the exceptions to the gender rule
//     (día, mapa, problemas, and section 2's mano) and on the nouns whose
//     gender the rule can't give (restaurante, ciudad), plus unos and unas.
//     Its other nouns (mesa, regalo, hermanas, vendedores) follow the rule.
//   - Ex. 5: seven of eight, one per form it asks for, and "esta" added
//     (below). Its "regalo … (cerca de mí)" asks for este again.
//   - Ex. 6 is the word list (below).
//   - Ex. 7 and 8 keep the sentences that teach something no other card
//     does: no "unos" before libros, "¿Qué tienen…?", buscar with para,
//     llevar, a demonstrative in a whole sentence. Their sentences with ser,
//     estar or ir are Lección 1 and 2 material, and their age and "to be"
//     sentences are the ser, estar o tener cards.
//
// Not made into cards: ex. 9 (true or false) and ex. 10 (questions on the
// story) test memory of the dialogue, not Spanish; ex. 11 (dictation) and
// ex. 12 and 13 (oral answers) need the audio.
//
// Vocabulary is ex. 6's list. Each noun carries the article the list gives
// it ("a book" → un libro, "the history" → la historia); "discounts" has
// none on the list and takes los, so the card shows its gender. "That table
// over there" is learned in the phrase "Está en aquella mesa", and "these two
// books" in the demonstrative card "Voy a llevar ___ dos libros": their
// forms are what the lesson tests, and a phrase card would pass the wrong
// one. Added from the dialogue: la librería, el vendedor, los audífonos,
// Buenos días, Muchas gracias and por favor.
//
// Where this departs from the sheets, or adds to them:
//   - The age phrase is "Tengo 17 años", in figures, as the French Leçon 3
//     did: the sheet's "diecisiete" is beyond this lesson's numbers (6 to
//     10), and a word card can take only one spelling of the Spanish.
//   - The "ser, estar o tener" cards are not an exercise on the sheet. They
//     are its sentences: ex. 7 "My sister is nine years old", ex. 1 "Ellos
//     tienen ocho y diez años", ex. 8 "Why are you guys tired?" and "This
//     book is very beautiful", ex. 7 "They have earphones on the second
//     floor" (as "Los audífonos ___ en el segundo piso").
//   - The demonstrative cards put the sheet's distance cue (cerca de mí,
//     cerca de ti, lejos) before the arrow, not in brackets after the
//     sentence. Its "………… librería es muy bonita. (lejos)" is asked with
//     cerca de mí, for esta, which ex. 5 never asks for; aquella is asked by
//     "Los libros están en ___ mesa".
//   - Ex. 2 and 3 answers are accepted with or without the Sí the prompt
//     shows, with or without the subject pronoun, and with the noun kept or
//     replaced. "¿Eres mexicano?" also takes mexicana; "¿Tu hermana tiene
//     diez años?" also takes 10 in figures. "¿Los libros están en la
//     mesa?" takes no "ellos": Spanish leaves the subject out for things.
//   - "en el segundo piso" is "on the second floor / on the third floor
//     (US)": in Mexico the floor above the planta baja (ground floor) is the
//     primer piso, so the segundo piso is an American's third floor.
//   - "llevar" is "to take / to carry": the dialogue's "Voy a llevar" is
//     buying ("I'll take"), and to carry is its everyday sense.
//   - "mi papá" is "mi papá / mi padre": papá is the everyday Mexican word,
//     and a teacher accepts the standard padre for "my father" too.
//   - Taken out on 2026-10-25, at the owner's word (no masculine/feminine
//     cards: "remove the noun-gender cards too"): the eight article gap
//     cards from ex. 4 (el día, la mano, los problemas, el restaurante, un
//     mapa, una ciudad, unos audífonos, unas ideas) and the two "del o de
//     la" cards. A word card still asks each noun with its article.
//
