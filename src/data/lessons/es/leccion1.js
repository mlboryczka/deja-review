//
// Card shapes:
//   "yo" / "I"                                      the subject pronouns, both ways round
//   "ser (presente) → yo" / "soy"                   ser, six persons; the line comes from the shape
//   "ser → Mi esposa y yo ___ de Chicago"           ex. 1: ser after a name, a noun, usted
