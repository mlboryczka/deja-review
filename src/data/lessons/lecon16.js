// WHY THE PRONOUN POINTS ARE ALL → CARDS. A word or phrase card is marked
// fuzzily, and this lesson's points are a letter or two, or a change of word
// order. Shown the English, the phrase cards let through exactly what the
// lesson is about (each checked with lessoncheck --try):
//   - the past participle that doesn't change: "Je l'ai vu hier soir" passes
//     for "Je l'ai vue hier soir", and "Comment tu les as rencontré ?" for
//     "… rencontrés ?";
//   - the pronoun in the English place: "Je cherche les" passes for "Je les
//     cherche", because the same words in another order count as close
//     enough;
//   - the wrong one of le and lui: "Je lui ai écouté" passes for "Je l'ai
//     écouté", "Je l'ai demandé" for "Je lui ai demandé", and "Tu les parles
//     souvent ?" for "Tu leur parles souvent ?";
//   - me and te not shortened: "Je ne te entends pas" passes.
