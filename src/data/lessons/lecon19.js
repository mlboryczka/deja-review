// WHY EVERY CONDITIONAL THE LESSON IS ABOUT IS AN ARROW CARD. Phrase cards are
// marked fuzzily, and the conditional is one or two letters away from the
// tenses it gets confused with: the imparfait (je travaillais / je
// travaillerais), the future (je serai / je serais) and, after si, the
// conditional where the imparfait belongs (si j'aurais / si j'avais). Shown
// the English, the phrase cards let these through as close enough (each
// tried with lessoncheck --try): "Je serai moins stressé" for "Je serais
// moins stressé"; "Je travaillais …" and "Je travaillerai pour une
// association caritative"; "J'aimais aller là-bas avec toi", "Il m'a dit
// qu'il aimait venir", "Tu voulais de l'eau ?" and "Tu allais voir le
// médecin …"; "Si j'aurais plus de temps, je ferais de la peinture", "… si
// tu aurais un rhume ?" and "… si tu pourrais faire un vœu ?", the very
// mistake the If tab warns about; "S'il ferait beau, qu'est-ce que tu ferais
// ?", the same mistake; "Je suis moins stressé", the present; "Pouvez-vous
// ouvrir la porte …" for "Pourriez-vous …"; and "Il m'a dit qu'il aimera
// venir", the future after a past verb. (A few are refused because the words
// differ more: "J'étais moins stressé", "Je voudrais aller là-bas avec
// toi".) So the forms are checked exactly by the drills, the polite rewrites
// (her ex. 3) and the si gap cards (her lesson and ex. 4), which refuse each
// of those (tried: pourrais, aurais, serais and aurait after si; venais,
// allais, faisais, dormais, dînait, pouvais and suis in the result; voulait
// and voudra for voudrait; pourrez and pouviez for pourriez), and the phrase
// cards are there for whole sentences and their meaning. The one mix-up no
// exact card refuses is aimera for aimerait after "il m'a dit que": a gap
// card there would also take aimait ("he told me he liked coming"), and the
// aimer drill checks only the form.
//
// Shown the French, the English side has the same blind spot: "I will be
// less stressed", "It will be amazing!", "I worked for a charity", "I will
// like to go there with you", "He told me he will like to come", "If I had
// more time, I will do some painting" and "Will you go to the doctor if you
// had a cold?" pass as close enough (tried), and so does the present, a
// letter or two from the "I'd …" answers: "I like to go there with you", "I work
// for a charity", "I am less stressed", "If I had more time, I paint", "He
// told me he likes to come" (tried). A card can't refuse those without
// refusing "I'd …", and typed English is never marked exactly, so no card
// checks that a student reading the French sees the would; the exact
// drills, polite cards and si cards check that the forms are made.
//
// The same holds for ouvre and ouvert, two letters apart: "Le restaurant
// ouvert à 11h" passes for "Le restaurant ouvre à 11h", "Tu sais si le bar
// est ouvre ?" for "… est ouvert ?", and "J'ai vendre ma voiture …" for "J'ai
// vendu …" (tried). So the choice between the verb and ouvert is on exact gap
// cards: "ouvrir → Le restaurant ___ à 11h et ferme à 15h" (ouvre; "est
// ouvert" and "ouvert" refused) and "ouvrir → Le magasin est ___" (ouvert;
// "ouvre" refused), with -e and -s on "La porte est ___" and "Les magasins
// sont ___". The participles ouvert and vendu are checked exactly by the
// passé composé drills.
//
// "Would" for a past habit is the imparfait, not the conditional (her
// ATTENTION box). The French of a gap card can't show the English "would", so
// two cards put the same verb, with the same person, in the two tenses:
// "dîner → Si le resto était ouvert ce soir, on ___ là-bas" (dînerait, her
// ex. 4 no. 19) and "dîner → Quand on était petits, tous les soirs, on ___
// ensemble" (dînait; her Leçon 13 dialogue, "Tous les soirs, on dînait
// ensemble", which her translation gives as "Every night we would have
// dinner together"). Each refuses the other's answer, and each refused
// answer is wrong there. Her no. 19 needed "ce soir" for that: si with the
// imparfait in both halves can mean "whenever" for a past habit (Académie
// française, Dictionnaire, 9th ed., article "si", II: "Si les enfants
// faisaient la sieste, la nourrice sortait se promener", glossed "à chaque
// fois que, lorsque"), so "Si le resto était ouvert, on dînait là-bas",
// "whenever the restaurant was open, we ate there", is good French, and
// exactly the would for a habit this lesson teaches. "Ce soir" rules that
// reading out. Her no. 17 gains "en ce moment" for the same reason ("Si tu
// étais moins stressé, tu dormais mieux" is right as a past habit). Both
// sections show the same line, naming the two tenses, so the line doesn't
