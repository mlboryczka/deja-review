//
// THE DRILLS. Each of the sheet's three model verbs is drilled in full
// (trabajar, comer, vivir), because each group has its own endings and -er
// and -ir part only with nosotros (comemos, vivimos). Ver gets one drill,
// yo (veo), the only form the sheet calls irregular; its other forms are
// regular, and "Vemos la tele juntos" asks for one.
//
// THE POSSESSIVES ARE GRAMMAR CARDS, NOT TRANSLATIONS. A phrase card is
// marked fuzzily, so "sus libro" and "mis papá" pass as close enough for
// "su libro" and "mi papá": the very mistake the sheet's ¡Atención! box is
// about. So every possessive the lesson teaches is an exact gap card: mi or
// mis, tu or tus, su or sus, and nuestro, nuestra, nuestros or nuestras. What
// su means (his, her, its, their, your) is learned on two phrase cards, "su
// libro" (the sheet's own example) and "sus hijos", where the English is
// the answer and the fuzzy marking does no harm.
//
// EX. 3 IS ANSWERED KEEPING THE NOUN. "Sí, vive en Nueva York" is good
// Spanish, but it skips the possessive the exercise is for, so the line
// above those cards asks for the noun, and only answers that keep it (with
// mi or mis) are accepted, with or without the Sí. This is the French
// Leçon 4's ex. 3 rule.
//
// Sampled, not transcribed:
//   - Ex. 1 keeps seven of its sixteen sentences, one verb per card and every
//     person at least once: camino (yo), lees (tú, after the verb), enseña
//     (a name), cenamos and escribimos (nosotros, -ar and -ir), aprenden
//     (ustedes), viven (a plural noun). Its surfear, andar, hablar, comer,
//     trabajar and invitar sentences, and its second caminar and vivir
//     ones, repeat one of those.
//   - Ex. 2 keeps one card per person: tú → yo, ustedes → nosotros, ellas,
//     and two names. Its other six are the same switches with other verbs.
//   - Ex. 3 keeps tu → mi with a noun subject (hermano, mamá), tus → mis
//     with a plural (papás), and tus → mis after the verb (¿Invitas mucho a
//     tus papás?). "¿Es tu hermano?", "¿Tu hija se llama Emma?" and "¿Tu
//     hermano tiene hijos?" repeat them; "¿Los papás de James están
//     jubilados?" would be answered with sus or with the name, and its
//     answers are too many to mark exactly.
//   - Ex. 5 (my dad, his dad, our mom…) becomes the possessive gap cards, in
//     the dialogue's and exercises' sentences, and the two su phrase cards.
//   - Ex. 6 and 7 keep the sentences that teach something no other card
//     does: "¿Dónde vives?", "Vemos la tele juntos" (ver), "Es enfermera" (no
//     una before a job), "Le encanta surfear". The rest repeat the gap and
//     answer cards, or are Lección 2 and 3 material.
//
// Not made into cards: ex. 8 (true or false) and ex. 9 (questions on the
// story) test memory of the dialogue, not Spanish; ex. 10 (dictation) and
// ex. 11 and 12 (oral answers) need the audio.
//
// Vocabulary is ex. 4's list, split so that the verbs come before the
// drills and the family before the possessives. Left out: "a dad", which is
// Lección 3's "mi papá"; "her name is …", which is Lección 1's "Mi esposa
// se llama Linda"; and "Ah, okay!", whose Spanish is the English word ok,
// and whose comma would let "Ah" alone pass. "She loves …" is learned in
// "Le encanta surfear". "A friend", "nice" and "retired" are listed "masc.
