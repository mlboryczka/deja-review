// sheets (adapted from Laura Caufour's LFL METHOD): the lesson (Emilia tells
// her Australian friend Matt about her summer in Oaxaca; ver and venir in the
// present and the preterite; the negative preterite; a before a person; "to
// drive"; the weather; numbers 100 to 999) and the exercise sheet. There is
// no answer key: every answer here is the one a Mexican Spanish teacher
// would give.
//
// The students have done Lessons 1–9: ser, estar, ir, tener, the regular
// present, querer, poder, gustar, describing people, saber, the regular
// preterite, the time and the date, and Lesson 9's hacer, irregular
// preterites and verb + verb. No card asks for more than that plus this
// lesson.
//
// Each entry is [front, back, category, section]. The front is always the
// Spanish.
//
// Card shapes:
//   "ver (presente) → tú" / "ves"             drill; its line comes from its shape
//   "¿Trabajaste en julio? → No, …"           answer no in a full sentence (ex. 3 and 4)
//   "a, al o nada → Vi ___ Hugo en la playa"  a before a person, or nothing (ex. 6)
//   "hacer, estar o tener → Hoy ___ nublado"  the weather verb, in the present
//   "Llueve → en pretérito" / "Llovió"        the weather in another tense
//   "365 → en letras"                          the number in words (ex. 10)
//   two-way word (V) and phrase (E) cards for ex. 8 and samples of ex. 7 and 9
//
// WHY THE WEATHER VERBS AND THE "A" ARE ON EXACT CARDS. Phrase cards are
// marked fuzzily: "Voy a visitar mis abuelos en diciembre", with no a, is two
// letters from the right sentence and passes as close enough; so does "No
// puede tomar" for "No pude tomar". So the choices this lesson is about (the a
// before a person; hacer, estar or tener for the weather) are asked on exact
// gap cards, and the phrase cards are there for meaning. "Es nublado" also
// passes for "Está nublado" on its phrase card, which is why "Hoy ___
// nublado" is a gap card too. "Es calor" is far enough from "Hace calor" to
// fail on its phrase card.
//
// Sampled, not transcribed: each card teaches something no other does.
//   - Ver and venir: the six-person drill in the present, except ver's yo
//     form (veo), which Lesson 4 drills and which owns that front; in the
//     preterite, five persons (ustedes has the ellos / ellas form, asked in
//     the present). Venir's preterite was in Lesson 9's table too, but Lesson 9
//     asks it only in sentences, so its drills are here.
//   - Ex. 3 (answer no, preterite): one answer per switch (tú → yo with tus →
//     mis and te → me, ustedes → nosotros, an impersonal hizo) and per
//     irregular verb. Ex. 4 (present): the new verbs in the yo and nosotros
//     forms (vengo, veo, vemos). Its weather and "tienes calor" items are
//     asked by the weather cards; "¿Sabes manejar?" by "No sé manejar".
//   - Ex. 6: six of its twelve, two of each answer, with tener among the
//     "nothing" ones.
//   - Ex. 7: the four "to drive" sentences that show the rule. Ex. 9: three
//     sentences a learner needs whole.
//   - Ex. 10: every irregular hundred (quinientos, setecientos, novecientos),
//     ciento for 101, doscientos, two with tens and units, and the
//     feminine (doscientas personas). 100 itself is cien, asked in Lesson 9.
//
// Not made into cards: ex. 1 and 2 (write any sentence) and ex. 11 (three
// negative sentences of your own) have no single answer, so the drills ask
// for every form; ex. 5 (write the question) has many right questions per
// answer; ex. 12 is a dictation and ex. 13 is oral.
//
// Vocabulary is the ex. 8 list, with these left out: "in July" (Lesson 8's
// months), "pretty" (bonito, Lesson 3), "the city" (Lesson 3), "to go on
// vacation" (Lesson 9), "my boss" (Lesson 8), the cognates "a state",
// "practical" and "amazing" (increíble), and "for a week" (una semana, with
// no por; "por una semana" is heard too, and a phrase card could take only
// one). "Villages" is un pueblo, with its article; "wonderful beaches" keeps
// the sheet's plural, unas playas maravillosas. The six weather phrases are
// their own section, before the weather gap cards. "It rained" is asked as
// "Llueve → en pretérito".
//
// Where this departs from the sheets:
//   - Ex. 3 asks "¿Visitaron la ciudad?" after a question with ustedes. Alone
//     on a card it can mean "Did they visit the city?", so the card says
//     "¿Ustedes visitaron la ciudad?".
//   - Ex. 6's empty gap ("nada (—)") is typed as nada.
//   - Ex. 7's English sentences become phrase cards whose English carries the
//     verb wanted, "(with ir)" or "(tú, with venir)": "Manejé a Oaxaca" is
//     understood, and the cards are there to teach the usual way.
//   - "¿Te gustó Oaxaca? → No, …" also takes "No, no me gustó", a whole
//     sentence in Spanish, as Lesson 5's gustar card does.
//   - The answer-no cards don't take an answer that starts with a single no
//     ("No trabajé en julio"): the marker ignores commas, so it would also
//     pass "No, trabajé en julio", the one-no mistake the notes warn about.
//     As in Lessons 5 and 6, they take "No, no …", or a sentence that starts
//     with a pronoun or a time ("Yo no trabajé…", "En julio no trabajé").
//   - "Ella no quiso visitar la ciudad" carries "(with ella)" on its English
//     side: "No quiso visitar la ciudad" is just as right, and a phrase card
//     can take only one.
//   - The gap card "¡___ 35 grados!" is ex. 9's "It's 35 degrees!".
//   - No slips found in the sheets.
//
// Checked 2026-10-22 by an independent reader: 11 fixes.
//
// The notes are the lesson's grammar in English (the sheet explains in
// Spanish), restructured on the rules in .claude/skills/building-lessons.
