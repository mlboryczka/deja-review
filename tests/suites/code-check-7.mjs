// Code check of 7 November 2026, problems 98 to 113 (feedback, disputes and
// card fixes). No browser: what can be run as a function is run, and what
// lives in a page is checked in the source for the rule the fix put there.
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { checker } from "../check.mjs";
import { courseOfFeedback, describeFeedback } from "../../api/_lib/feedbackReview.js";
import { REVIEW_SYSTEM, MARK_SYSTEM, PUNCTUATION_RULE } from "../../api/_lib/exercises.js";
import { FEEDBACK_REVIEW_VERSION } from "../../src/lib/feedbackReviewVersion.js";
import { claudeError } from "../../api/_lib/podcasts.js";
import Anthropic from "@anthropic-ai/sdk";

const ck = checker();
const read = (f) => readFileSync(new URL(`../../${f}`, import.meta.url), "utf8");
const app = read("src/FlashcardApp.jsx");
const bf = read("src/BetaFeedback.jsx");
const review = read("api/review-answer.js");
// The hook's file imports the browser's Supabase client, so its pure function
// is taken out of the source and run.
const hook = read("src/useAnswerDispute.js");
const acceptedLine = new Function(`${hook.slice(hook.indexOf("export function acceptedLine")).replace("export function", "function")}; return acceptedLine;`)();

// 98: a feedback list that cannot be read says so.
ck("98 an unread feedback list is an error, not 'No open feedback.'",
   /setLoadError\(error\.message/.test(app) && /loadError \? \(\s*<div[^>]*data-feedback-load-error/.test(app));

// 99: no card is attached from the end-of-set screen.
ck("99 feedback gets no card once the set is done", app.includes('currentCard={mode === "study" && !sessionDone ? card : null}'));

// 100: a removal is logged only after it worked.
{
  const at = app.indexOf("const ok = await deleteCard(editingCard.row_id);");
  const seg = app.slice(at, at + 400);
  ck("100 the delete is logged after deleteCard succeeded", at > 0 && /if \(!ok\) return;[\s\S]*logCorrection\(/.test(seg));
  ck("100 nothing is logged before the removal", !/logCorrection\(\{\s*category,\s*action: CORRECTION_ACTIONS\.DELETE/.test(app));
}

// 101: an accepted answer that was not saved is said so.
ck("101 recordAlternate says whether it kept the answer", /return !error;/.test(review));
ck("101 Accept anyway fails plainly when it was not kept", /if \(!kept\) \{\s*return res\.status\(500\)/.test(review));
ck("101 an accepted dispute carries kept: false", /kept: false/.test(review) && /feedbackVerdict\.kept === false/.test(app));

// 102: the card a note was started on stays with it.
ck("102 the note keeps the card it was started on", /setDraftCard\(\(d\) => d \|\| currentCard/.test(bf) && /const card = draftCard \|\| currentCard/.test(bf));
ck("102 Send attaches that card", /const cardContext = \(attachCard && card\)/.test(bf) && !/currentCard\.f/.test(bf));
ck("102 a moved-on student can switch to the card on screen", /data-use-screen-card/.test(bf));

// 103: the old-disputes script asks the app's own question.
{
  const s = read("scripts/resolve-disputes.mjs");
  ck("103 it asks through askClaude, not a prompt of its own", /askClaude\(/.test(s) && !/claude-opus-5/.test(s) && !/You adjudicate/.test(s));
}

// 104: the feedback script refuses what it cannot read.
{
  const env = { ...process.env, SUPABASE_URL: "http://127.0.0.1:1", SUPABASE_SERVICE_ROLE_KEY: "x" };
  const run = (...a) => spawnSync("node", ["scripts/resolve-feedback.mjs", ...a], { env, encoding: "utf8", cwd: new URL("../../", import.meta.url).pathname });
  const odd = run("#x", "--note", "n", "--apply");
  ck("104 an id it cannot read stops the run, named", odd.status === 1 && /Not understood: #x/.test(odd.stderr), odd.stderr);
  const none = run("--note", "n", "--apply");
  ck("104 --apply with no id and no --all stops", none.status === 1 && /needs at least one feedback id/.test(none.stderr), none.stderr);
  const ok = run("#57", "42,43", "--note", "n");
  ck("104 #57 and 42,43 are understood (it goes on to read the list)", !/Not understood/.test(ok.stderr), ok.stderr);
  ck("104 the setup file numbers feedback as the live database does", /beta_feedback \(\s*--[^\n]*\n\s*id bigint generated by default as identity/.test(read("supabase/schema.sql")));
}

// 109: Spanish pages count as Spanish.
ck("109 a Spanish page with no card is Spanish", courseOfFeedback({ page: "Spanish exercises/leccion-1" }) === "es" && courseOfFeedback({ page: "Spanish study" }) === "es");
ck("109 a French page is still French", courseOfFeedback({ page: "study" }) === "fr" && courseOfFeedback({ page: null }) === "fr");
ck("109 the Spanish note is given to a cardless Spanish feedback", /Spanish part of the app/.test(describeFeedback({ page: "Spanish dialogues/all", message: "x" }, null)));
ck("109 re-review of open entries is asked for", FEEDBACK_REVIEW_VERSION >= 3);

// 110: Claude is told how Spanish is marked.
{
  const text = describeFeedback({ page: "Spanish study", message: "x", card_context: { course: "es", front: "a", back: "b" } }, null);
  ck("110 numbers, months and verb forms exact; gender on words; caderno; almost", /must be typed exactly/.test(text) && /word cards/.test(text) && /caderno/.test(text) && /almost/.test(text));
}

// 111: a plain sentence, never Anthropic's raw text.
ck("111 the card dispute no longer returns err.message", !/json\(\{ error: err\.message \}\)/.test(review) && /claudeError\(err, "look at your answer"\)/.test(review));
{
  const raw = '529 {"type":"error","error":{"type":"overloaded_error","message":"Overloaded"}}';
  const e = new Anthropic.APIError(529, { type: "error" }, raw, new Headers());
  const r = claudeError(e, "look at your answer");
  ck("111 an overloaded Claude gives a sentence with no JSON", r.status === 503 && !/[{}]/.test(r.json.error), r.json.error);
}
ck("111 class reading says it plainly too", /claudeError\(e, "read this class"\)/.test(read("api/cahier-parse.js")) && /CLASS_NOT_READ/.test(read("api/cahier-sync.js")));

// 112: an acceptance that was not kept still says so after the lesson reopens.
ck("112 the line reads the saved answer when the hook's state is gone",
   /not kept/.test(acceptedLine(null, { accepted: "missing" })) && /couldn’t be kept/.test(acceptedLine(null, { accepted: "unkept" })) && /from now on/.test(acceptedLine(null, { accepted: true })));
ck("112 an unkept acceptance is not added to what marks answers",
   /how !== "kept"/.test(read("src/ExercisesPage.jsx")) && /how !== "kept"/.test(read("src/DialoguesPage.jsx")));

// 113: the second look keeps the comma after an opening No.
ck("113 both prompts carry the same comma rule", REVIEW_SYSTEM.includes(PUNCTUATION_RULE) && MARK_SYSTEM.includes(PUNCTUATION_RULE) && /No, tengo tiempo/.test(REVIEW_SYSTEM));
ck("113 no double quotes in the marking prompts", !/"/.test(REVIEW_SYSTEM) && !/"/.test(MARK_SYSTEM));

const n = ck.fails();
console.log(n ? `\n  FAILED: ${n}` : "\n  all checks passed");
process.exit(n ? 1 : 0);
