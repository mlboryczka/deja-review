// Jessica; the negative with gustar; encantar and gustar más; a mí también,
// a mí tampoco; the days of the week) and the exercise sheet. The sheets
// have no answer key: every answer here was written for the app, as a
// Mexican Spanish teacher would mark it.
//
// Each entry is [front, back, category, section]. The front is always the
// Spanish.
//
// The students have done Lessons 1–5: ser, estar and ir, tener, regular
// verbs, possessives, querer and poder, the negation with no, tú and usted.
// No card asks for more than that plus this lesson.
//
// Card shapes:
//   "gusta o gustan → ¿Te ___ los tacos?"           choose the form (ex. 1)
//   "me, te, le, nos o les → A James ___ gusta…"     choose the pronoun (ex. 2)
//   "yo + el cine → gustar"                          make the sentence (from ex. 8)
//   "¿Te gustan los tacos? → Sí, …"                  answer yes in a full sentence (ex. 3)
//   "¿Te gustan los mercados? → No, …"               answer no in a full sentence (ex. 4)
//   "Me gustan los tacos → encantar"                 rewrite with the word given
//   "Me gusta el cine → estoy de acuerdo"            react: a mí también, tampoco, sí, no (ex. 5)
//   "domingo → ___ voy a ir al cine"                 on a day: no word for "on" (ex. 8)
//   "domingo → el día siguiente"                     the next day (ex. 6)
//   "el parque" / "the park"                         words and phrases, both ways round
//
// NO DRILL FOR GUSTAR. Gustar doesn't change with the person: the person is
// the me, te, le, nos or les in front of it, and the verb changes only with
// the thing liked (gusta, gustan). A drill "gustar (presente) → yo" would
// also accept "yo me gusta" (the app adds the subject to a drill's answer),
// so ex. 1 and ex. 2 stand in for it.
//
// WHY "YO GUSTO" IS ON EXACT CARDS. Phrase cards are marked with typo
// tolerance, and "Yo gusto el cine" is three edits from "Me gusta el cine":
// close enough, on the very mistake her ¡Atención! box is about. So making
// a gustar sentence from nothing is an exact card ("yo + el cine →
// gustar"), and so are "no … nada", encantar and más: "Me gusta la playa"
// would pass for "No me gusta nada la playa" on a phrase card, missing two
// words. The phrase cards are there for meaning.
//
// WHY "NO ME GUSTA…" ALONE IS NOT ACCEPTED ON THE ANSWER-NO CARDS. The
// marker ignores commas, so "No me gustan los mercados" and the mistake
// "No, me gustan los mercados" ("No, I like markets") are the same typed
// answer. The ex. 4 cards therefore want the double no the prompt starts
// ("No, no me gustan…"), and accept an answer without the first No only
// where it starts with "A …" ("A mí no me gustan los mercados"). Their line
// says to start with No, since the answer-yes cards take their answer
// without the Sí.
//
// A blind spot of the fuzzy cards: on "el sábado" / "on Saturday" and "Los
// sábados vamos al parque", the English speaker's "en el sábado" passes as
// close enough, since it contains the answer. The exact card "domingo → ___
// voy a ir al cine" (her ex. 8 no. 14) marks it wrong, and a bare "domingo"
// too. Her rule (no word for "on") is in the Days tab.
//
// WHAT WAS SAMPLED, AND WHAT WAS LEFT:
//   - Ex. 1: six of ten, one per case: a plural noun, an infinitive with a
//     plural person (nos gusta andar), two infinitives next to a plural noun
//     (le gusta caminar y comer tacos), a plural person with a plural noun,
//     mucho between, and no before le.
//   - Ex. 2: five of ten: a mí and nos, a plural noun and les, usted, a
//     name, ustedes. "A mí ___" (me) and "¿A ti ___" (te) say their answer.
//   - Ex. 3 and 4: one card per change of person (te → me, ustedes → nos,
//     tus → mis, usted → me in ex. 3; a name, te → me, ustedes → nos, tu →
//     mi in ex. 4).
//   - Ex. 5 asks you to react "según tu opinión", which has no single
//     answer. Each card says after the arrow whether you agree, in the
//     words of her own table (estoy de acuerdo, no estoy de acuerdo), and
//     there is one card for each of her four reactions.
//   - Ex. 6: two of six, one of them wrapping round the week (domingo).
//   - Ex. 7 (the word list): "to ride a bike" (andar en bicicleta) is on
//     Lesson 4's list and "something" (algo) on Lesson 3's, so they have no
//     card here. "afterwards" (después) has none either: Lesson 2 has only
//     "después de", "after". "Me too!", "Me
//     neither!", "I do" and "I don't" are the ex. 5 cards; "not at all" is
//     the "no … nada" card. All seven days are cards: her section 6 teaches
//     them all, though her list asks for three.
//   - Ex. 8 gave the four gustar sentences ("yo + el cine → gustar",
//     "nosotros + ir al mercado → encantar", "mis papás + la comida mexicana
//     → encantar", "él + leer → gustar": nos. 1, 3, 8 and 12, the last asked
//     as a sentence, not a question), "Me gusta la playa → más" (no. 13),
//     "domingo → ___ voy a ir al cine" (no. 14) and the phrase card "Los
//     sábados vamos al parque" (no. 7). The rest repeat a card, or are
//     negative sentences a phrase card can't mark (nos. 4, 5, 9, 11). No. 12
//     is an exact card, not a phrase card: as a phrase card, "Gusta leer"
//     and "¿A él gusta leer?" passed for "¿Le gusta leer?".
//   - Ex. 9 and 10 test memory of the story; ex. 11 and 12 are audio.
//
// WHERE THE CARDS GO BEYOND HER SHEETS:
//   - The "→ gustar / encantar", "→ no … nada" and "→ más" cards are not
//     exercises of hers. They are built from her sentences (ex. 8, the
//     dialogue, her section 4 table), and every answer is a sentence of
//     hers or one made the same way.
//   - Ex. 3 no. 7, "¿Le gusta el chile? (usted)", is asked as "¿A usted le
//     gusta el chile?", which says usted without a bracket.
//   - Every answer card takes its answer with or without a mí, a nosotros
//     and so on, and the short "Sí, me gusta" (the thing is understood).
//     The yes cards also take their answer without the Sí. "¿A tus papás
//     les gusta caminar?" also takes "a ellos" or no name at all.
//   - Ex. 6 also takes the next day with el ("el jueves").
//
// Slips in the sheets: none found that a card or note uses.
//
// THE NOTES are her grammar translated into English and rebuilt to the
// notes rules in .claude/skills/building-lessons/SKILL.md. Six tabs:
//   Gustar    her section 1, and answering yes
//   A mí      her section 2
//   Negative  her section 3, and answering no
//   Encantar  her section 4
//   Agree     her section 5
//   Days      her section 6
// The examples are hers (lesson, dialogue, exercises). Sentences that are
// not on her sheet, kept because a card needs them:
//   - Gustar, "Answering yes", and Negative, "Answering no": te → me, le
//     (usted) → me, les (ustedes) → nos, tus → mis (her ex. 3 and 4 ask it
//     without saying it).
//   - A mí: the table of a + person → me, te, le, nos, les, and "When you
//     are one of the people, use nos" (her example "A mi esposa y a mí nos
//     encanta" shows it; ex. 2 no. 4 asks it).
//   - Negative: "With a person, no goes after them" (her example "A
//     Jessica no le gusta…" shows it).
//   - Encantar: "nada goes after gusta, and no stays in front" and "más
//     goes straight after gusta" (her examples show both).
// The lesson's one "The trap:" is her ¡Atención! box: never yo gusto.
//
