//   "pero" / "but"                                  ex. 3 word list, both ways round
//   "¿De dónde eres?" / "Where are you from? …"     the dialogue and ex. 4, both ways round
//
// Left out: section 1 (how the letters sound, where the stress falls, the
// upside-down ¿ and ¡) and section 2 (the alphabet) have no card and no tab:
// they are about pronunciation and spelling aloud, which no typed card can
// check, and the marker ignores accents, ¿ and ¡ anyway. Ex. 5 and 6 (true
// or false, questions on the dialogue) test the story, not Spanish; ex. 7
// and 8 (dictation, oral answers) need the audio.
//
// Sampled, not transcribed. Ex. 1 keeps the five sentences whose subject the
// drills don't show: a name (Lucía), two names, "mi esposa y yo", usted, and
// ustedes after the verb ("¿De dónde ___ ustedes?"); its sentences with
// yo, tú, ella, nosotros or ellos ask what the drills already ask. Ex. 2
// keeps one card for each change of person: tú → yo, usted → yo, ustedes →
// nosotros, a name → ella, two names → ellos, and tu → mi. Its "¿Eres
// profesora de español?", "¿Eres de Los Ángeles?" and "¿Tú eres James?" are
// tú → yo again; "¿Usted es el esposo de Lucía?" needs el, an article
// Lección 1 doesn't teach; "¿Marta y Ana son mexicanas?" is the ellas card's
// job (below). Ex. 4 keeps the sentences that teach something no other card
// does.
//
// WHY SER, THE PRONOUNS AND THE NATIONALITIES ARE ALSO ON EXACT CARDS. Word
// and phrase cards are marked with typo tolerance: "Ella eres mexicana"
// passes for "Ella es mexicana", "ellas" for "she", "ellos" for "they (women
// only)", "nosotras" for "we (men, or men and women)", and "Soy mexicano,
// pero vivo en Los Ángeles" for the woman's sentence. So every form of ser is
// asked exactly (the six drills, the ex. 1 gaps and the ex. 2 answers), and
// the two nationality endings that aren't just -o to -a by two gap cards.
// The phrase cards are there for meaning. Closing the gap on the phrase
// cards needs a change to the app's fuzzy marking, not to this file.
//
// THE ESTAR SENTENCES ARE PHRASE CARDS ONLY. The sheet's ATENCIÓN box says
// estar comes in Lección 2 and gives four sentences to learn by heart
// (¿Por qué estás…?, Estoy aquí con mi esposo, ¿Estás casado?, Estamos
// juntos desde hace dos años). Three are phrase cards; the fourth is asked as
// ex. 4's "¿Por qué estás en Los Ángeles?" (the same sentence with the city
// the exercise asks for, and no "los" question: "en Estados Unidos" and "en
// los Estados Unidos" are both right, and the second fails a phrase card).
// Ser or estar is not asked exactly until Lección 2, which teaches it; until
// then "¿Por qué eres en Los Ángeles?" would pass that card as close enough.
//
// "por qué" / "why": "porque" ("because") passes for it as close enough (one
// space apart). Lección 2 teaches the pair on exact cards.
//
// Vocabulary is ex. 3's list. Its nouns stay bare (esposo, esposa, año,
// clase de español), as in the French Leçon 1: el and la are Lección 2's
// and 3's, so no Lección 1 card asks for an article. "Teacher" and "Mexican"
// are listed "masc. & fem.", so the front gives both forms ("profesor /
// profesora") and either is right. "I am (ser)" is the yo drill, not a word
// card. "Where … from?" is learned in "¿De dónde eres?", and "hello" is
// "hola" (Lección 2's "Hi!" is the same word and stays here).
//
// Where this departs from the sheets, or adds to them:
//   - The pronoun cards' English follows the sheet's table ("informal",
//     "formal", "plural") in plain words: "one person you know well", "one
//     person, politely", "several people".
//   - The two nationality cards are not an exercise on the sheet. They are
//     its Nationalities section put into its sentences (Jessica es
//     estadounidense) and its examples (español → españoles).
//   - Ex. 2 answers are accepted with or without the Sí the prompt already
//     shows, with or without the subject pronoun, and with the name kept
//     ("Sí, Lucía es de Guadalajara"): all are what a teacher would accept.
//   - Hints that pin down the Spanish: "Mi esposa se llama Linda" and "me
//     llamo" say "(literally: …)", because "mi nombre es" is right too;
//     "Soy mexicana, pero…" says "(said by a woman)".
//   - "Son profesores" is ex. 4's "They are teachers" without the pronoun,
//     as Spanish usually says it; "Ellos son profesores" still passes (as
//     close enough), and its English also takes "You are teachers", which
//     son means with ustedes.
//   - Taken out on 2026-10-25, at the owner's word ("don't test simple
